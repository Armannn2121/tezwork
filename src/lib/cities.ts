const BY_ID = new Map(LIST.map((c) => [c.id, c]));

export const CITY_IDS = LIST.map((c) => c.id);
export const DEFAULT_CITY = 'Алматы';

export const cityName = (id: string) => (getLang() === 'ru' ? BY_ID.get(id)?.ru ?? id : id);

// Тізім ағымдағы тілдегі алфавит бойынша
export const sortedCities = () =>
  [...CITY_IDS].sort((a, b) => cityName(a).localeCompare(cityName(b), getLang()));

// Екі тілде де іздейді: «караг» → Қарағанды
export function searchCities(q: string) {
  const s = q.trim().toLowerCase();
  if (!s) return sortedCities();
  return sortedCities().filter((id) => id.toLowerCase().includes(s) || (BY_ID.get(id)?.ru ?? '').toLowerCase().includes(s));
}
